// Regenerates src/abi/generated.ts from the Foundry build output (run `forge build` in the repository root first).
// CI runs this and fails if the committed file differs, so the monitor's ABIs cannot drift from the contracts.
import {readFileSync, writeFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "..", "..", "out");
const target = join(here, "..", "src", "abi", "generated.ts");

const contracts: Array<[name: string, exportName: string]> = [
  ["LiquidityManager", "liquidityManagerAbi"],
  ["GuardianController", "guardianControllerAbi"],
  ["SaharaTimelock", "saharaTimelockAbi"],
  ["CCIPPoolAdapter", "ccipPoolAdapterAbi"],
];

let source = "// Generated by scripts/gen-abi.ts from the Foundry build output. Do not edit.\n";
for (const [name, exportName] of contracts) {
  const artifact = JSON.parse(readFileSync(join(outDir, `${name}.sol`, `${name}.json`), "utf8")) as {abi: unknown[]};
  source += `\nexport const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
}
writeFileSync(target, source);
console.log(`wrote ${target}`);
